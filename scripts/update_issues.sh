### Роли

| Роль | Возможности |
|------|-------------|
| `MEMBER` | `/mytasks`, смена статуса своих задач, участие в синках |
| `MANAGER` | Всё выше + `/board`, `/tasks @user`, сводка синка, назначение задач |
| `ADMIN` | Всё выше + привязка чатов к проекту, выдача инвайтов, управление ролями |

### Привязка роли к чату

Один пользователь может быть MEMBER в одном чате и MANAGER в другом.
Хранится: `UserGroupRole(userId, groupId, role)`.

### Управление ролями

**Через бота (для ADMIN):**
- `/role @username manager` — назначить менеджером в текущем чате
- `/role @username member` — понизить до участника
- `/roles` — список участников с ролями

**Через REST (для интеграции):**
- `PUT /api/groups/{groupId}/members/{userId}/role`

### Проверка роли в запросах
- `UserPrincipal` должен содержать роль в контексте группы
- Эндпоинты с `@PreAuthorize("hasRole('MANAGER')")` или аналог через `GroupId` из запроса

### Критерий готовности
- MEMBER не может вызвать `/board` (бот отвечает «недостаточно прав»)
- ADMIN через `/role` меняет роль, изменение сразу вступает в силу
- В `/board` видно у каждого участника его роль

